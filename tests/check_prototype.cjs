// Optional browser verification. No production data or external network required.
'use strict';
const {chromium} = require(process.env.LAC_PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({headless:true});
  try {
    const base = process.argv[2] || 'http://127.0.0.1:8876';
    const artifacts = path.resolve('.cache/prototype');
    fs.mkdirSync(artifacts,{recursive:true});
    const errors = [];
    const page = await browser.newPage({viewport:{width:1500,height:1020}});
    page.on('pageerror', error => errors.push(error.message));
    const forbidden=[];
    const checkRequest=req=>{if(req.url().startsWith('data:'))return;const url=new URL(req.url());if(url.origin!==new URL(base).origin||url.pathname.startsWith('/api/'))forbidden.push(req.url());};
    page.on('request',checkRequest);
    await page.goto(base);
    await page.locator('[data-node="doc"]').waitFor();
    await page.screenshot({path:path.join(artifacts,'laboratorio-desktop.png'),fullPage:true});
    await page.locator('[data-edge="relation"]').focus();
    await page.locator('[data-edge="relation"]').press('Enter');
    await page.getByRole('button',{name:'Comparar fontes',exact:true}).click();
    await page.getByRole('heading',{name:'Compare antes de relacionar'}).waitFor();
    await page.locator('#bench [data-source="doc"]').click();
    assert.match(await page.locator('#dialogContent').innerText(),/conteúdo da alteração não foi recuperado/);
    await page.getByRole('button',{name:'Fechar',exact:true}).click();
    await page.getByRole('button',{name:'Confirmar vínculo',exact:true}).click();
    assert.match(await page.locator('#inspectorContent').innerText(),/Confirmação demonstrativa/);
    await page.getByRole('button',{name:'No tempo',exact:true}).click();
    await page.locator('#trajectory [data-select="decision"]').click();
    await page.getByRole('button',{name:'Relações',exact:true}).click();
    await page.locator('[data-node="decision"].selected').waitFor();
    await page.getByRole('button',{name:'Fixar posição',exact:true}).click();
    const before=await page.locator('[data-node="decision"]').evaluate(el=>parseFloat(el.style.left));
    await page.getByRole('button',{name:'Mover cartão para esquerda',exact:true}).click();
    assert.equal(await page.locator('[data-node="decision"]').evaluate(el=>parseFloat(el.style.left)),before-24);
    await page.reload();
    assert.equal(await page.locator('[data-node="decision"]').evaluate(el=>parseFloat(el.style.left)),before-24);
    await page.locator('[data-node="decision"] .pin-indicator').waitFor();
    const handle=await page.locator('[data-drag="decision"]').boundingBox();
    await page.mouse.move(handle.x+handle.width/2,handle.y+handle.height/2);
    await page.mouse.down();
    await page.mouse.move(handle.x+handle.width/2-20,handle.y+handle.height/2+10,{steps:5});
    await page.mouse.up();
    assert.ok(await page.locator('[data-node="decision"]').evaluate(el=>parseFloat(el.style.left))<before-24);
    const oldTransform=await page.locator('#world').getAttribute('style');
    await page.locator('#mapViewport').focus();
    await page.locator('#mapViewport').press('ArrowRight');
    assert.notEqual(await page.locator('#world').getAttribute('style'),oldTransform);
    await page.getByRole('button',{name:'Memória',exact:true}).click();
    await page.locator('[data-memory="concise"]').uncheck();
    await page.getByRole('button',{name:'Fechar',exact:true}).click();
    await page.getByRole('button',{name:'Encontrar no contexto'}).click();
    await page.locator('#searchInput').fill('protocolo');
    assert.equal(await page.locator('#searchResults button').count(),2);
    await page.locator('[data-search-select="doc"]').click();
    await page.getByRole('button',{name:'Examinar conexão'}).count().then(async count=>{if(count)await page.getByRole('button',{name:'Examinar conexão'}).click();});
    for(const scenario of ['processing','paused','unavailable','missing','empty']) {
      await page.locator('#scenario').selectOption(scenario);
      assert.equal(await page.locator(scenario==='empty'?'#emptyState':'#stateBanner').isVisible(),true);
    }
    await page.getByRole('button',{name:'Voltar ao exemplo',exact:true}).click();
    await page.locator('#question').fill('O que mudou?');
    await page.getByRole('button',{name:'Perguntar ao assistente demonstrativo'}).click();
    assert.match(await page.locator('#answer').innerText(),/event:102/);
    await page.getByRole('button',{name:'Registrar',exact:true}).click();
    await page.locator('#captureText').fill('<script>throw new Error("must remain text")</script>');
    await page.getByRole('button',{name:'Manter rascunho nesta aba'}).click();
    await page.getByRole('button',{name:'Registrar',exact:true}).click();
    assert.match(await page.locator('#captureText').inputValue(),/<script>/);
    await page.getByRole('button',{name:'Fechar',exact:true}).click();
    await page.getByRole('button',{name:'Restaurar exemplo',exact:true}).click();
    const mobile = await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
    mobile.on('pageerror', error=>errors.push(error.message));
    mobile.on('request',checkRequest);
    await mobile.goto(base);
    assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
    await mobile.screenshot({path:path.join(artifacts,'laboratorio-mobile.png'),fullPage:true});
    await mobile.getByRole('button',{name:'Examinar conexão'}).click();
    await mobile.getByRole('button',{name:'Comparar fontes',exact:true}).click();
    await mobile.getByRole('button',{name:'Confirmar vínculo',exact:true}).click();
    assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
    assert.deepEqual(errors,[]);
    assert.deepEqual(forbidden,[]);
    console.log('OK: desktop/mobile, comparison, origin, review, selection, persisted layout, memory, search, states, capture, no external requests or JS errors.');
    console.log('Screenshots: ' + artifacts);
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
